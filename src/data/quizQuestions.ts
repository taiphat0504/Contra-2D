// Helper to get questions for chosen subject
export function getQuestionsForSubject(subjectId: SubjectId): QuizQuestion[] {
  if (subjectId === 'all') {
    return [...QUIZ_DATABASE].sort(() => Math.random() - 0.5);
  }
  const filtered = QUIZ_DATABASE.filter(q => q.subject === subjectId);
  return filtered.length > 0 
    ? [...filtered].sort(() => Math.random() - 0.5)
    : [...QUIZ_DATABASE].sort(() => Math.random() - 0.5);
}
